CREATE TABLE users.change_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name  TEXT NOT NULL,
    operation   TEXT NOT NULL,
    row_id      TEXT NOT NULL DEFAULT '',
    old_data    JSONB,
    new_data    JSONB,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by  BIGINT,
    CONSTRAINT ck_users_change_log_operation CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE OR REPLACE FUNCTION users.capture_row_change()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    secret_columns TEXT[] := ARRAY['password_hash', 'password_history', 'mfa_secret_enc'];
BEGIN
    INSERT INTO users.change_log (table_name, operation, row_id, old_data, new_data, changed_by)
    VALUES (
        TG_TABLE_NAME,
        TG_OP,
        CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END::text,
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) - secret_columns END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) - secret_columns END,
        CASE WHEN TG_OP = 'DELETE' THEN OLD.updated_by ELSE NEW.updated_by END
    );
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_users_change_log
AFTER INSERT OR UPDATE OR DELETE ON users.users
FOR EACH ROW EXECUTE FUNCTION users.capture_row_change();

