#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = join(root, "packages", "contracts", "src");
const spec = JSON.parse(readFileSync(join(root, "packages", "contracts", "gen", "openapi.json"), "utf8"));
const methods = ["get", "head", "post", "put", "patch", "delete"];

const identifier = (value) =>
  value
    .replace(/(^|[^a-zA-Z0-9]+)([a-zA-Z0-9])/g, (_, __, char) => char.toUpperCase())
    .replace(/[^a-zA-Z0-9]/g, "");
const schemaName = (operationId) => `${operationId.replace(/^[A-Z]/, (char) => char.toLowerCase())}Schema`;

function resolve(schema) {
  if (!schema?.$ref) return schema ?? {};
  return spec.components.schemas[schema.$ref.split("/").at(-1)] ?? {};
}

function zod(schema) {
  const resolved = resolve(schema);
  if (resolved.allOf?.length)
    return resolved.allOf.map(zod).reduce((left, right) => `z.intersection(${left}, ${right})`);
  if (resolved.oneOf?.length) return `z.union([${resolved.oneOf.map(zod).join(", ")}])`;
  if (resolved.enum?.length) return `z.enum(${JSON.stringify(resolved.enum)})`;
  if (resolved.const !== undefined) return `z.literal(${JSON.stringify(resolved.const)})`;
  if (resolved.type === "object" || resolved.properties) {
    const required = new Set(resolved.required ?? []);
    const properties = Object.entries(resolved.properties ?? {}).map(([name, property]) => {
      const expression = zod(property);
      return `  ${JSON.stringify(name)}: ${required.has(name) ? expression : `${expression}.optional()`},`;
    });
    return `z.object({\n${properties.join("\n")}\n}).strict()`;
  }
  if (resolved.type === "array") {
    let expression = `z.array(${zod(resolved.items)})`;
    if (resolved.minItems !== undefined) expression += `.min(${resolved.minItems})`;
    if (resolved.maxItems !== undefined) expression += `.max(${resolved.maxItems})`;
    return expression;
  }
  if (resolved.type === "integer" || resolved.type === "number") {
    let expression = `z.number()${resolved.type === "integer" ? ".int()" : ""}`;
    if (resolved.minimum !== undefined) expression += `.min(${resolved.minimum})`;
    if (resolved.maximum !== undefined) expression += `.max(${resolved.maximum})`;
    return expression;
  }
  if (resolved.type === "boolean") return "z.boolean()";
  let expression = "z.string()";
  if (resolved.format === "email") expression += ".email()";
  else if (resolved.format === "uri") expression += ".url()";
  if (resolved.minLength !== undefined) expression += `.min(${resolved.minLength})`;
  if (resolved.maxLength !== undefined) expression += `.max(${resolved.maxLength})`;
  if (resolved.pattern) expression += `.regex(/${resolved.pattern.replaceAll("/", "\\/")}/)`;
  if (resolved.nullable === true) expression += ".nullable()";
  return expression;
}

const pathsByTag = new Map();
const validators = [];
for (const [path, pathItem] of Object.entries(spec.paths)) {
  for (const method of methods) {
    const operation = pathItem[method];
    if (!operation) continue;
    for (const tag of operation.tags ?? []) {
      if (!pathsByTag.has(tag)) pathsByTag.set(tag, new Set());
      pathsByTag.get(tag).add(path);
    }
    const body = operation.requestBody?.content?.["application/json"]?.schema;
    if (body) validators.push(`export const ${schemaName(operation.operationId)} = ${zod(body)};`);
  }
}

const generatedFiles = [];
for (const [tag, paths] of pathsByTag) {
  const typeName = `${identifier(tag)}Paths`;
  const union = [...paths]
    .sort()
    .map((path) => JSON.stringify(path))
    .join(" | ");
  const output = join(source, `${tag.replace(/^_/, "").replace(/[^a-z0-9-]/gi, "-")}.ts`);
  writeFileSync(
    output,
    `// Generated by scripts/generate-contract-modules.mjs.\nimport type { paths } from "./gen";\n\nexport type ${typeName} = Pick<paths, ${union}>;\n`,
  );
  generatedFiles.push(output);
}
const schemasOutput = join(source, "schemas.ts");
writeFileSync(
  schemasOutput,
  `// Generated by scripts/generate-contract-modules.mjs.\nimport { z } from "zod";\n\n${validators.join("\n\n")}\n`,
);
generatedFiles.push(schemasOutput);
execFileSync(process.execPath, [
  join(root, "node_modules", "@biomejs", "biome", "bin", "biome"),
  "format",
  "--write",
  ...generatedFiles,
]);
console.log(`generated ${pathsByTag.size} tag modules and ${validators.length} Zod request schemas`);
